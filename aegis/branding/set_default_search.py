#!/usr/bin/env python3
"""Aegis Browser - default search engine transform (runs in CI before gn gen).

Reorders third_party/search_engines_data/resources/definitions/regional_settings.json
so every region's search-engine list puts DuckDuckGo first (the first entry is
the fresh-profile default) and Google last. Google stays in the list so the
choice screen / settings still offer it - we change the default, not the menu.

The file lives in the DEPS checkout external/search_engines_data.git (not in
the src git repo), so it cannot carry a git patch - this hook edits it after
gclient sync, before json_to_struct regenerates prepopulated_engines.cc/h.

Layout verified @ chromium 156.0.8078.79 (DEPS rev
5dc9f1afd38a8ac2b26b1972eb4fc1bbd5754e8c): elements.<REGION>.search_engines
is an array of engine refs like "&google"; first element = default.

Idempotent: re-running on an already-transformed file is a no-op.
Usage: set_default_search.py <chromium-src-dir>
"""
import json
import os
import re
import sys

GOOGLE = "&google"
DDG = "&duckduckgo"


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "."
    path = os.path.join(
        src, "third_party/search_engines_data/resources/definitions/regional_settings.json")
    if not os.path.isfile(path):
        print(f"Aegis DSE: {path} not found (upstream layout changed?) - skipping")
        return
    raw = open(path, encoding="utf-8").read()
    # The file carries full-line // comments; strip only whole-line comments
    # (never inside-string slashes).
    stripped = re.sub(r"^\s*//.*$", "", raw, flags=re.M)
    data = json.loads(stripped)
    elements = data.get("elements") or {}
    if not isinstance(elements, dict) or not elements:
        print("Aegis DSE: no elements map in regional_settings.json - skipping")
        return

    changed = 0
    ddg_missing = []
    for region, cfg in elements.items():
        engines = cfg.get("search_engines")
        if not isinstance(engines, list) or not engines:
            continue
        if GOOGLE not in engines:
            continue
        rest = [e for e in engines if e not in (GOOGLE, DDG)]
        if DDG not in engines:
            ddg_missing.append(region)
            new = rest + [GOOGLE]
        else:
            new = [DDG] + rest + [GOOGLE]
        if new != engines:
            cfg["search_engines"] = new
            changed += 1

    if changed == 0:
        print(f"Aegis DSE: already applied ({len(elements)} regions untouched)")
        return

    header = ("// Regional search-engine ordering modified by Aegis Browser:\n"
              "// DuckDuckGo first (fresh-profile default), Google demoted to last.\n"
              "// Generated by aegis/branding/set_default_search.py - upstream\n"
              "// format is JSON-with-comments consumed by tools/json_to_struct.\n")
    body = json.dumps(data, indent=2, ensure_ascii=False)
    with open(path, "w", encoding="utf-8") as f:
        f.write(header + body + "\n")
    print(f"Aegis DSE: {changed}/{len(elements)} regions -> default DuckDuckGo, "
          f"google demoted to last (regions without DDG in list: "
          f"{len(ddg_missing)}{': ' + ','.join(ddg_missing[:6]) if ddg_missing else ''})")


if __name__ == "__main__":
    main()
