#!/usr/bin/env python3
"""Aegis Browser - generate the full launcher icon set (Android + desktop).

Icon source: aegis/branding/logo/aegis-logo-rounded.png (curved-corner mark,
generated by round_logo.py from the master logo; falls back to the sharp
master if the rounded asset is absent).

Spacing rule (user spec): the mark must NOT touch the icon boundary - all
three sides (apex + two base corners) keep clear space, like the Brave /
Chromium launcher icons:
  - adaptive foreground vector : mark fits 46/108dp  (safe zone is 66dp,
    visible circle is 72dp -> mark = 64% of what the launcher shows)
  - legacy/composed bitmaps    : mark at 62% of the canvas
Outputs:
  icons/res_chromium_base/
    mipmap-{mdpi..xxxhdpi}/app_icon.png                  legacy launcher (48..192)
    mipmap-{mdpi..xxxhdpi}/layered_app_icon.png          composed adaptive (108..432)
    mipmap-{mdpi..xxxhdpi}/layered_app_icon_background.png  bg layer (108..432)
    mipmap-nodpi/layered_app_icon_foreground.xml         traced VectorDrawable
    drawable/themed_app_icon.xml                         monochrome vector
    preview.png                                          human check
  icons/desktop/
    product_logo_{16,24,32,48,64,128,256}.png            Linux menu / .deb icons
    aegis.ico                                            Windows .exe / shortcut
    desktop_preview.png                                  human check
"""
import os
import sys

import cv2
import numpy as np
from PIL import Image, ImageDraw

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BRAND = os.path.join(REPO, "aegis", "branding")
LOGO_ROUND = os.path.join(BRAND, "logo", "aegis-logo-rounded.png")
LOGO_MASTER = os.path.join(BRAND, "logo", "aegis-logo.png")
OUT = os.path.join(BRAND, "icons", "res_chromium_base")
OUT_DESKTOP = os.path.join(BRAND, "icons", "desktop")

BG = (7, 7, 7)          # brand black (#070707), sampled from the master logo
WHITE = (255, 255, 255)

LEGACY = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
LAYERED = {"mdpi": 108, "hdpi": 162, "xhdpi": 216, "xxhdpi": 324, "xxxhdpi": 432}

BITMAP_FILL = 0.62      # legacy + composed bitmaps (safe even if circle-masked)
FG_FIT_DP = 46.0        # adaptive foreground vector, in the 108dp viewport
THEMED_FIT_DP = 34.0    # monochrome themed icon, in the 90dp viewport


def load_mark():
    """White-mark alpha float 0..1 from the rounded asset (or sharp master)."""
    if os.path.exists(LOGO_ROUND):
        img = Image.open(LOGO_ROUND)
        a = np.asarray(img.getchannel("A"), dtype=np.float32) / 255.0
        ys, xs = np.where(a > 0.02)
        a = a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
        print(f"icon source: aegis-logo-rounded.png "
              f"(curved corners, mark {a.shape[1]}x{a.shape[0]})")
        return a
    print("icon source: aegis-logo.png (sharp fallback - rounded asset missing!)")
    rgb = np.asarray(Image.open(LOGO_MASTER).convert("RGB"), dtype=np.float32)
    lum = rgb.mean(axis=2) / 255.0
    mask = lum > 0.5
    rows = np.where(mask.any(axis=1))[0]
    top, bot = rows[0], rows[-1]
    cols = np.where(mask[top:bot + 1].any(axis=0))[0]
    alpha = lum[top:bot + 1, cols[0]:cols[-1] + 1]
    return np.clip((alpha - 0.35) / 0.35, 0.0, 1.0)


def compose_mark(alpha, box, fill_frac=BITMAP_FILL):
    """Full-bleed brand-black square, white mark fitted to fill_frac of it."""
    inner = int(round(box * fill_frac))
    h, w = alpha.shape
    k = inner / max(h, w)
    tw, th = max(1, int(round(w * k))), max(1, int(round(h * k)))
    a = Image.fromarray((alpha * 255).astype(np.uint8)).resize((tw, th), Image.LANCZOS)
    canvas = Image.new("L", (box, box), 0)
    canvas.paste(a, ((box - tw) // 2, (box - th) // 2))
    out = Image.new("RGBA", (box, box), BG + (255,))
    white = Image.new("RGBA", (box, box), WHITE + (255,))
    out.paste(white, (0, 0), canvas)
    return out


def trace_paths(alpha, viewport=108.0, fit=FG_FIT_DP, center=None):
    """Trace contours -> Android pathData string in the given viewport.

    Returns (pathData, polys_in_viewport, iou). IoU compares the simplified
    polygons against the tracing raster, so fidelity is measured, not assumed.
    """
    if center is None:
        center = viewport / 2.0
    h, w = alpha.shape
    scale = 720.0 / max(h, w)
    small = cv2.resize(alpha, (int(round(w * scale)), int(round(h * scale))),
                       interpolation=cv2.INTER_AREA)
    sh, sw = small.shape
    mask8 = (small >= 0.5).astype(np.uint8)
    contours, hier = cv2.findContours(mask8, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_SIMPLE)
    k = fit / max(sh, sw)                      # contours live in the 720-space!
    ox, oy = center - (sw * k) / 2.0, center - (sh * k) / 2.0
    parts, polys_vp, polys_small = [], [], []
    for c in contours:
        if cv2.contourArea(c) < 6:                       # drop speckles
            continue
        eps = 0.0008 * cv2.arcLength(c, True) + 0.25
        poly = cv2.approxPolyDP(c, eps, True).reshape(-1, 2).astype(np.float64)
        polys_small.append(poly)
        pts = [f"{ox + x * k:.2f},{oy + y * k:.2f}" for x, y in poly]
        parts.append("M" + " L ".join(pts) + " Z")
        polys_vp.append(np.column_stack([ox + poly[:, 0] * k, oy + poly[:, 1] * k]))
    assert parts, "no contours traced"

    # --- fidelity check: hierarchy-aware raster vs original mask ----------
    raster = np.zeros_like(mask8)
    depth = {}
    for i, h4 in enumerate(hier[0]):
        d, p = 0, h4[3]
        while p != -1:
            d += 1
            p = hier[0][p][3]
        depth[i] = d
    for i, c in enumerate(contours):
        if cv2.contourArea(c) < 6:
            continue
        cv2.fillPoly(raster, [c.astype(np.int32)], 255 if depth[i] % 2 == 0 else 0)
    inter = np.logical_and(raster > 0, mask8 > 0).sum()
    union = np.logical_or(raster > 0, mask8 > 0).sum()
    iou = inter / union if union else 0.0

    xs = np.concatenate([p[:, 0] for p in polys_vp])
    ys = np.concatenate([p[:, 1] for p in polys_vp])
    print(f"vector bbox in viewport: x {xs.min():.1f}-{xs.max():.1f}, "
          f"y {ys.min():.1f}-{ys.max():.1f} (target fit {fit} @ center {center})")
    print(f"trace fidelity IoU: {iou:.4f}")
    assert iou > 0.97, f"traced vector deviates from the mark (IoU {iou:.3f})"
    return " ".join(parts), polys_vp, iou


def vector_xml(width_dp, viewport, fill, path, even_odd=True):
    fo = ' android:fillType="evenOdd"' if even_odd else ""
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Aegis launcher icon - traced from aegis/branding/logo/'
            f'aegis-logo-rounded.png (curved corners) -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{width_dp}dp"\n'
            f'    android:height="{width_dp}dp"\n'
            f'    android:viewportWidth="{viewport}"\n'
            f'    android:viewportHeight="{viewport}">\n'
            f'    <path\n'
            f'        android:pathData="{path}"\n'
            f'        android:fillColor="{fill}"{fo} />\n'
            f'</vector>\n')


def tile(size, alpha, fill, radius_frac):
    """Rounded-corner brand-black tile with the white curved mark centered."""
    S = size * 4
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    ImageDraw.Draw(img).rounded_rectangle(
        [0, 0, S - 1, S - 1], radius=int(S * radius_frac), fill=BG + (255,))
    h, w = alpha.shape
    inner = S * fill
    k = inner / max(h, w)
    tw, th = max(1, int(round(w * k))), max(1, int(round(h * k)))
    a = Image.fromarray((alpha * 255).astype(np.uint8)).resize((tw, th), Image.LANCZOS)
    img.paste(WHITE + (255,), ((S - tw) // 2, (S - th) // 2), a)
    return img.resize((size, size), Image.LANCZOS)


def mono_glyph(alpha, size=22):
    """Mark-only dark silhouette for upstream product_logo_22_mono.png."""
    inner = round(size * 0.62)
    h, w = alpha.shape
    k = inner / max(h, w)
    tw, th = max(1, round(w * k)), max(1, round(h * k))
    a = Image.fromarray((alpha * 255).astype(np.uint8)).resize((tw, th), Image.LANCZOS)
    out = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    out.paste(Image.new("RGBA", (tw, th), (32, 33, 36, 255)),
              ((size - tw) // 2, (size - th) // 2), a)
    return out


def desktop_tiles(alpha):
    """Linux product_logo_*.png + Windows .ico assets."""
    os.makedirs(OUT_DESKTOP, exist_ok=True)
    sizes = [16, 24, 32, 48, 64, 128, 256]
    tiles = {}
    for s in sizes:
        if s <= 24:
            fill, rad = 0.72, 0.15
        elif s <= 32:
            fill, rad = 0.66, 0.18
        else:
            fill, rad = 0.62, 0.22
        t = tile(s, alpha, fill, rad)
        tiles[s] = t
        t.save(os.path.join(OUT_DESKTOP, f"product_logo_{s}.png"))
    mono_glyph(alpha).save(os.path.join(OUT_DESKTOP, "product_logo_22_mono.png"))
    ico_path = os.path.join(OUT_DESKTOP, "aegis.ico")
    tiles[256].save(ico_path, format="ICO",
                    sizes=[(s, s) for s in sizes],
                    append_images=[tiles[s] for s in sizes if s != 256])
    # preview strip on both light and dark background
    px = 256
    strip = Image.new("RGB", (px * len(sizes) + 10 * (len(sizes) + 1), px + 20), (255, 255, 255))
    strip.paste(Image.new("RGB", (strip.width, strip.height), (255, 255, 255)), (0, 0))
    for i, s in enumerate(sizes):
        bgc = (255, 255, 255) if i % 2 == 0 else (24, 24, 24)
        cell = Image.new("RGB", (px + 10, px + 20), bgc)
        t = tiles[s].resize((min(px, s * 8),) * 2, Image.NEAREST) if s < 64 else tiles[s]
        cell.paste(t, (5 + (px - t.width) // 2, 10 + (px - t.height) // 2), t)
        strip.paste(cell, (10 + i * (px + 10), 0))
    strip.save(os.path.join(OUT_DESKTOP, "desktop_preview.png"))
    print("desktop icons ->", OUT_DESKTOP)


def main():
    alpha = load_mark()

    for d in [f"mipmap-{d}" for d in LEGACY] + ["mipmap-nodpi", "drawable"]:
        os.makedirs(os.path.join(OUT, d), exist_ok=True)

    # --- bitmaps -----------------------------------------------------------
    for dens, size in LEGACY.items():
        compose_mark(alpha, size, fill_frac=BITMAP_FILL).save(
            os.path.join(OUT, f"mipmap-{dens}", "app_icon.png"))
    for dens, size in LAYERED.items():
        compose_mark(alpha, size, fill_frac=BITMAP_FILL).save(
            os.path.join(OUT, f"mipmap-{dens}", "layered_app_icon.png"))
        Image.new("RGB", (size, size), BG).save(
            os.path.join(OUT, f"mipmap-{dens}", "layered_app_icon_background.png"))

    # --- vectors -----------------------------------------------------------
    fg_path, polys_vp, iou = trace_paths(alpha, viewport=108, fit=FG_FIT_DP)
    with open(os.path.join(OUT, "mipmap-nodpi", "layered_app_icon_foreground.xml"), "w") as f:
        f.write(vector_xml(108, 108, "#FFFFFF", fg_path))
    mono_path, _, iou2 = trace_paths(alpha, viewport=90, fit=THEMED_FIT_DP, center=45.0)
    with open(os.path.join(OUT, "drawable", "themed_app_icon.xml"), "w") as f:
        f.write(vector_xml(90, 90, "#000000", mono_path))

    # --- desktop -----------------------------------------------------------
    desktop_tiles(alpha)

    # --- preview: LEFT = vector as a round launcher renders it,
    #               MID/RIGHT = legacy bitmaps at 192/96 -------------------
    vp = 108.0
    PX = 432
    vx = np.zeros((PX, PX), np.float32)
    for p in polys_vp:
        cv2.fillPoly(vx, [np.column_stack([p[:, 0] * PX / vp, p[:, 1] * PX / vp]).astype(np.int32)], 1.0)
    vec = np.full((PX, PX, 3), BG, np.uint8)
    vx3 = np.clip(vx * 255.0, 0, 255).astype(np.uint8)
    for ch in range(3):
        vec[:, :, ch] = np.maximum(vec[:, :, ch], vx3)
    vec_img = Image.fromarray(vec).convert("RGBA")
    mask = Image.new("L", (PX, PX), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, PX - 1, PX - 1), fill=255)
    round_img = Image.new("RGBA", (PX, PX), (0, 0, 0, 0))
    round_img.paste(vec_img, (0, 0), mask)
    legacy192 = compose_mark(alpha, 192, fill_frac=BITMAP_FILL)
    legacy96 = compose_mark(alpha, 96, fill_frac=BITMAP_FILL)
    strip = Image.new("RGB", (PX + 192 + 96 + 30, PX), (30, 30, 30))
    strip.paste(round_img.convert("RGB"), (0, 0))
    strip.paste(legacy192.convert("RGB"), (PX + 15, 0))
    strip.paste(legacy96.convert("RGB"), (PX + 192 + 15, 0))
    strip.save(os.path.join(OUT, "preview.png"))

    print("foreground pathData chars:", len(fg_path))
    print("OK ->", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
